import { chromium } from "playwright";
import fs from "node:fs";
const BASE = "http://localhost:3000";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
page.setDefaultTimeout(90000);
await page.goto(BASE + "/login");
await page.getByRole("button", { name: /Instant Demo/ }).click();
await page.waitForURL("**/dashboard", { timeout: 90000 });
const sc = await page.request.get(BASE + "/api/forecast/scenario");
const scText = await sc.text();
console.log("SCENARIO_STATUS", sc.status());
console.log("SCENARIO_BODY", scText);
fs.writeFileSync(".codebenders/scratch/verify-scenario-before.json", scText);
const fc = await page.request.get(BASE + "/api/forecast?horizon=90");
const fcText = await fc.text();
console.log("FORECAST_BASELINE_STATUS", fc.status(), "LEN", fcText.length);
fs.writeFileSync(".codebenders/scratch/verify-forecast-baseline.json", fcText);
const inv = await page.request.get(BASE + "/api/invoices");
const invJson = await inv.json();
const rows = Array.isArray(invJson) ? invJson : (invJson.invoices ?? []);
const t = rows.find((r) => r.id === "inv_7426dfd29110a22c");
console.log("TARGET_INVOICE_FOUND", !!t, JSON.stringify(t ?? null));
await browser.close();
console.log("DONE");
