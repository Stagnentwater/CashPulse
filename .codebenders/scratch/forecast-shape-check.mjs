import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
page.setDefaultTimeout(60000);
await page.goto(BASE + "/login");
await page.getByRole("button", { name: /Instant Demo/ }).click();
await page.waitForURL("**/dashboard", { timeout: 90000 });
await page.getByText("Total Owed to Me", { exact: true }).waitFor();
await page.goto(BASE + "/forecast");
await page.waitForLoadState("networkidle");
await page.waitForTimeout(2000);
const body = (await page.locator("body").innerText()).replace(/\s+/g, " ");
console.log("FORECAST_BODY_LEN", body.length);
console.log("FORECAST_BODY", body.slice(0, 1200));
const api = await (await page.request.get(BASE + "/api/forecast?horizon=90")).text();
console.log("API_FORECAST_LEN", api.length, "HAS_LIVE_CHECK_TITLE", api.includes("Live check bill"));
console.log("API_FORECAST_HEAD", api.slice(0, 400));
await browser.close();
console.log("DONE");
