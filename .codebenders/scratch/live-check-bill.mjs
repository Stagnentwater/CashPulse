import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const TITLE = "Live check bill 1000";
const log = (...a) => console.log(...a);
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
page.setDefaultTimeout(90000);
await page.goto(BASE + "/login");
await page.getByRole("button", { name: /Instant Demo/ }).click();
await page.waitForURL("**/dashboard");
const forecastTab = await context.newPage();
await forecastTab.goto(BASE + "/forecast");
await forecastTab.waitForLoadState("networkidle");
await forecastTab.waitForTimeout(2000);
log("STALE_TAB_HAS_BILL_BEFORE", (await forecastTab.locator("body").innerText()).includes(TITLE));
const dueDate = new Date(Date.now() + 3 * 864e5).toISOString().slice(0, 10);
const bill = await page.request.post(BASE + "/api/bills", { data: { title: TITLE, category: "SUPPLIER", amount: 1000, dueDate, isRecurringMonthly: false, isDeferrable: false } });
log("BILL_STATUS", bill.status(), (await bill.text()).slice(0, 300));
await forecastTab.waitForTimeout(15000);
log("STALE_TAB_HAS_BILL_AFTER_15S_NO_RELOAD", (await forecastTab.locator("body").innerText()).includes(TITLE));
const fresh = await context.newPage();
await fresh.goto(BASE + "/forecast");
await fresh.waitForLoadState("networkidle");
await fresh.waitForTimeout(2000);
log("FRESH_TAB_HAS_BILL", (await fresh.locator("body").innerText()).includes(TITLE));
const fc = await (await page.request.get(BASE + "/api/forecast?horizon=90")).text();
log("API_FORECAST_CONTAINS_TITLE", fc.includes(TITLE));
await browser.close();
log("DONE");
